import * as React from "react"

import { cn } from "@/lib/utils"
import { useViewportInsetBottom } from "@/lib/use-viewport-inset-bottom"

import { flattenChildren } from "@/lib/flatten-children"
import { ButtonMenuRow, isButton, isOverflow } from "./row"
import { PINNED_CLASS, barShapeClass } from "./pinning"
import {
  BAR_PLACEMENT_CLASS,
  barPlacementStyle,
  type ButtonMenuPlacement,
} from "./placement"

// Закрепление у нижнего края — поведение по умолчанию, а не опция «на
// всякий случай»: в макете так и написано — «Панель всегда закреплена в
// нижней части экрана» (Button Menu) и «Button Menu всегда закрепляется в
// нижней части контентной области и занимает всю ширину» (Black).
//
// Именно `sticky`, а не `fixed`: панель остаётся в потоке и упирается в
// низ своего контейнера, поэтому не наезжает на контент — макет отдельно
// оговаривает «Панель не должна перекрывать кнопку „Показать ещё“».
// `fixed` вырвал бы её из потока и как раз перекрыл бы. Из этого же
// следует, что закрепление работает относительно прокручиваемого
// контейнера: панель прижимается к низу контентной области, а не окна.

interface ButtonMenuProps extends React.ComponentProps<"div"> {
  /**
   * Прижимать панель к низу контейнера. По умолчанию включено — в макете
   * она всегда закреплена; выключайте, когда панель нужна обычным блоком
   * в потоке (например, внутри карточки).
   */
  pinned?: boolean
  /**
   * «Отлипшая» полоса — дизайн-чек от 08.09, замечание 9: в продукте такого
   * состояния быть не должно, но пропс заведён на будущее. Полоса становится
   * островом в потоке и получает скругления снизу, такие же как сверху.
   */
  detached?: boolean
  /**
   * Размещение на сетке: во всю полосу (12 колонок), слева или справа.
   * Дизайн-чек от 13.09, замечание 19 — см. `./placement`.
   */
  placement?: ButtonMenuPlacement
  /** Сколько колонок занимает панель при размещении слева/справа, 1…12. */
  span?: number
}

// Строчная панель инструментов в форме таблетки. Передавайте детьми
// экземпляры `Button`: по макету кнопка Primary (если она есть) всегда идёт
// первой слева (хотя первым слотом столь же законно может быть Secondary
// или серая — бренд-кнопку макет не навязывает), за ней — до трёх кнопок
// Secondary, упорядоченных от самой часто используемой.
//
// Дизайн-чек от 07.09, замечание 3: «Непоместившиеся кнопки должны уходить
// в многоточие. Либо 3 команды и многоточие (если всё влезло), либо если не
// влезло — то правые команды тоже должны уходить в многоточие». Раньше
// панель просто рисовала всё, что ей дали, и лишние кнопки вылезали за
// правый край. Теперь ряд меряется тем же механизмом, что и навигация
// шапки, табы и свитчер (`useOverflowCount`), а не поместившиеся кнопки
// уходят в меню «ещё» — своё, если вызывающий его не передал, или в конец
// переданного, если передал. Сам механизм с 08.09 живёт в `ButtonMenuRow` и
// переиспользуется рядами команд вне панели (дизайн-чек от 08.09, №3).
const ButtonMenu = React.forwardRef<HTMLDivElement, ButtonMenuProps>(function ButtonMenu({
  pinned = true,
  detached = false,
  placement = "full",
  span = 12,
  className,
  style,
  children,
  ...props
}, forwardedRef) {
  // Фрагменты раскрываются: кнопки в `<>…</>` — такие же кнопки ряда, а не
  // «прочее» за его пределами.
  const nodes = flattenChildren(children)
  // Всё, что не кнопка и не меню «ещё», рисуется как есть и в замер не
  // входит: панель не берётся угадывать, что это и как оно сжимается.
  const row = nodes.filter((node) => isButton(node) || isOverflow(node))
  const extras = nodes.filter((node) => !isButton(node) && !isOverflow(node))

  // Та же публикация занятой высоты, что и у чёрной панели: всё, что липнет
  // к низу вьюпорта (полоса прокрутки таблицы), обязано вставать над ней.
  // ref потребителя сливается с внутренним: `forwardRef` забирает его из
  // пропсов, и `{...props}` ниже уже не может перетереть замер.
  const ref = useViewportInsetBottom(pinned && !detached, forwardedRef)

  return (
    // Форма следует варианту `desktop:`: в мастере «ELK / button menu» (v2.0.0)
    // два размера — Desktop (1160×88) и Mobile (360×72).
    //
    // Дизайн-чек от 13.09, замечание 2 («у панели не должно быть
    // мобайл-версии») снят макетом: в Size=Mobile нет ни рамки, ни тени, ни
    // скруглений — это ряд кнопок с полями 16/16 снизу 24 на белой маске,
    // которая плавно проявляется снизу вверх (прозрачный верх → белый на
    // 64%), поэтому контент под панелью уходит под неё мягко. Первая кнопка
    // растянута (Primary `flex-1`), остальные — по содержимому.
    <>
      {/* Живой мастер «ELK / button menu» (v2.0.0) подтверждает исходное
          прочтение замечания 5 дизайн-чека: это панель, прижатая к низу, а
          не плавающая таблетка. Скруглены только верхние углы, рамка идёт
          только сверху и по бокам (снизу ни рамки, ни радиуса, потому что
          этот край стоит вплотную к низу вьюпорта или контейнера), плюс
          своя тень (смещение 0/4, размытие 12, #8B99A9 при 24%). Устаревший
          статичный превью-ассет, которым обосновывали прежний полностью
          скруглённый вид без рамки, старше этого мастера; верить надо живому
          компоненту.

          Рамка в макете лежит ВНУТРИ размера (панель 1160×88 при полях
          32 и рядах 56): CSS-рамка снаружи давала 89 и сдвигала кнопки на
          пиксель, поэтому поля уменьшены на толщину рамки (31/15).

          Ширину задаёт размещение на сетке: по умолчанию вся полоса, что и
          показывают макеты «Использование в макете» (кнопки жмутся влево,
          белая заливка добирает остаток), но 12 колонок перестали быть
          единственной возможностью — см. `./placement`. */}
      <div
        ref={ref}
        data-slot="button-menu"
        data-pinned={(pinned && !detached) || undefined}
        data-detached={detached || undefined}
        data-placement={placement}
        className={cn(
          "flex items-center gap-4 border-solid border-[var(--button-menu-border)] bg-[linear-gradient(to_bottom,rgb(255_255_255/0),var(--button-menu-bg)_64%)] px-4 pb-6",
          "desktop:border-t desktop:border-r desktop:border-l desktop:bg-none desktop:bg-[var(--button-menu-bg)] desktop:px-[31px] desktop:pt-[15px] desktop:pb-4 desktop:shadow-universal",
          BAR_PLACEMENT_CLASS[placement],
          detached
            ? barShapeClass({ detached, bordered: true })
            : "desktop:rounded-t-[16px]",
          pinned && !detached && PINNED_CLASS,
          className
        )}
        style={{ ...barPlacementStyle(placement, span), ...style }}
        {...props}
      >
        {/* Мерная зона — только ряд кнопок: `extras` в неё не входят, иначе
            панель считала бы их место свободным. */}
        <ButtonMenuRow size="lg" stretchFirst>
          {row}
        </ButtonMenuRow>
        {extras}
      </div>
    </>
  )
})

export { ButtonMenu }
export type { ButtonMenuProps }
