import * as React from "react"

import { cn } from "@/lib/utils"

/**
 * Инлайновый значок в хвосте строки не должен уезжать вниз один.
 *
 * Правило дизайнера: значок в конце строки (шеврон аккордеона, подсказка у
 * подписи поля) не переносится на новую строку в одиночку — он уходит вниз
 * только вместе с последним словом.
 *
 * ⚠️ **Неразрывного пробела для этого НЕ ХВАТАЕТ.** Разрыв случается не у
 * пробела, а на стыке «спейсер → значок»: перед атомарным инлайновым боксом
 * у браузера своя точка переноса. Прогон по 271 ширине (360…900, шаг 2)
 * даёт:
 *
 *   • обычный пробел                          — 14 одиноких значков
 *   • неразрывный пробел                      — 8
 *   • неразрывный пробел внутри самого значка — 14
 *   • обёртка `nowrap` вокруг ПАРЫ            — 0
 *
 * Отсюда приём двухчастный:
 *
 *   1. неразрывный пробел ставится ПСЕВДОЭЛЕМЕНТОМ (`::before` по
 *      `data-slot`, см. styles/base.css) — в разметке узла нет, символ в
 *      разметку не пишется: иначе он попадёт в выделение и в буфер обмена;
 *   2. сама обёртка несёт `white-space: nowrap` и держит этот пробел вместе
 *      со значком.
 *
 * Сильнее всех болело не место с аккордеоном, а информационное поле:
 * значок-подсказка у подписи уезжал вниз на 45 ширинах из 301, у значения —
 * на 36; после правки 0 и 0.
 *
 * ⚠️ **Обёртка обязана быть ОТДЕЛЬНЫМ узлом вокруг коробки значка, а не ею
 * самой.** Значок почти всегда `inline-flex`, то есть атомарный инлайновый
 * бокс, и точка переноса у браузера стоит ПЕРЕД ним. Слить обёртку со
 * значком — значит оставить эту точку снаружи `nowrap`, и приём перестаёт
 * работать. Замер собственного прогона (271 ширина, 200…740): слитый узел —
 * 24 одиноких значка, отдельная обёртка — 0.
 *
 * ⚠️ И проверять это надо ПРОГОНОМ ПО ДИАПАЗОНУ ширин с шагом 2, а не на
 * трёх контрольных: на 1920/1440/1280 одинокого значка не видно вовсе. В
 * сам прогон стоит подсаживать заведомо дефектный узел (значок с обычным
 * пробелом и без обёртки) — если аудит не нашёл ЕГО, сломан аудит, а не
 * каталог чист.
 */
function NoOrphan({
  className,
  children,
  ...props
}: React.ComponentProps<"span">) {
  return (
    <span
      data-slot="no-orphan"
      className={cn("whitespace-nowrap", className)}
      {...props}
    >
      {children}
    </span>
  )
}

export { NoOrphan }
