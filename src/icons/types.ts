import type { SVGProps } from "react"

/** В макете набор нарисован под каждый размер отдельно: `Size=16x16` и
 * `Size=24x24` — разные варианты, и глифы у них оптически исправлены, а не
 * отмасштабированы (у alert на 24px обводка 2px и ножка длиннее, чем у
 * увеличенного в 1,5 раза 16px). Поэтому `size` выбирает САМ РИСУНОК, а не
 * только коробку: передавайте `size={24}` везде, где иконка рисуется на
 * 24px, а раскладку по-прежнему задавайте `className="size-6"`.
 *
 * Дизайн-чек №3 №10: теперь оба начертания есть у всего набора (страница
 * ALL ICONS), а не у горстки иконок. Забыть `size={24}` в
 * месте, где коробка 24px, — самая частая ошибка: глиф не сломается, но
 * растянется из 16px и будет заметно жирнее макета. */
export interface IconProps extends SVGProps<SVGSVGElement> {
  size?: 16 | 24
}
