/**
 * Общие правила расположения выпадающих элементов кита (списки Select,
 * Combobox, Autocomplete, календарь Date Picker, меню «Ещё», Selection
 * Button, Filter Table, переполнения Tabs и Switcher).
 *
 * Дизайн-чек 08.10, замечание 6: «отступ 8 пикселей от вызывающего элемента.
 * По умолчанию раскрытие вниз или согласно правилам компонента. Но если
 * места во вьюпорте снизу мало, а сверху его больше — выпадающий элемент
 * должен вставать сверху с тем же отступом 8».
 *
 * Переворот вверх/вниз Base UI делает и сам (`collisionAvoidance.side:
 * "flip"`), но по умолчанию, когда список не влезает НИ снизу, НИ сверху, он
 * пробует ещё и боковые стороны (`fallbackAxisSide: "end"`) — календарь
 * Date Picker в невысоком окне уезжал ВПРАВО от поля, наполовину поверх него
 * (скриншот 06 чека — то же окно, где он резался снизу). `"none"` оставляет
 * только ось раскрытия: из двух сторон выбирается та, где места больше, а
 * высоту списка дальше режет `--available-height`.
 */
const POPUP_SIDE_OFFSET = 8

const POPUP_COLLISION = {
  side: "flip",
  align: "flip",
  fallbackAxisSide: "none",
} as const

/**
 * Поворот шеврона открытия (Правки UI-Kit от 25.10): у триггера один шеврон,
 * при открытии списка он поворачивается на 180° — 200 мс, ease-out — и
 * обратно при закрытии, а не подменяется значком «вверх» (смена значка
 * читалась вспышкой). Сам поворот (`group-data-popup-open/…:rotate-180`)
 * ставит компонент — у каждого своя группа; общее здесь только движение,
 * чтобы у Select, Combobox и SelectionButton оно не расходилось.
 */
const POPUP_CHEVRON_TRANSITION = "transition-transform duration-200 ease-out"

export { POPUP_CHEVRON_TRANSITION, POPUP_COLLISION, POPUP_SIDE_OFFSET }
