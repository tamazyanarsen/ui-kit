/** Короткий раздел из одной темы — их в дереве большинство. */
function simple(
  value: string,
  title: string,
  topicTitle: string,
  text: string
): HelpSection {
  return {
    value,
    title,
    topics: [
      {
        value: `${value}-1`,
        title: topicTitle,
        body: [{ kind: "text", text }],
      },
    ],
  }
}

