import { describe, expect, it } from "vitest"

import { NBSP, typograph } from "./typograph"

// Правки UI-Kit от 25.10, правило «Типограф — без висячих предлогов, союзов
// и частиц». В ожиданиях `~` — неразрывный пробел.
const t = (text: string) => typograph(text).replaceAll(NBSP, "~")

describe("typograph", () => {
  it("после слов из 1–2 букв", () => {
    expect(t("Настройте с компьютера")).toBe("Настройте с~компьютера")
    expect(t("Документ для просмотра и подписи")).toBe("Документ для~просмотра и~подписи")
    expect(t("В работе до 5 дней")).toBe("В~работе до~5 дней")
    expect(t("в и с тобой")).toBe("в~и~с~тобой")
  })

  it("после предлогов и союзов из списка", () => {
    for (const word of ["через", "между", "около", "чтобы", "когда", "либо", "безо"]) {
      expect(t(`${word} слово`)).toBe(`${word}~слово`)
    }
    expect(t("Через минуту")).toBe("Через~минуту")
  })

  it("не трогает длинные слова и окончания слов через дефис", () => {
    expect(t("Сводный расчёт проекта")).toBe("Сводный расчёт проекта")
    expect(t("кто-то пришёл")).toBe("кто-то пришёл")
    expect(t("Подпись документа")).toBe("Подпись документа")
  })

  it("ООО и ПАО не отрываются от названия", () => {
    expect(t("Клиент ООО «Ромашка»")).toBe("Клиент ООО~«Ромашка»")
    expect(t("Банк ПАО Сбербанк")).toBe("Банк ПАО~Сбербанк")
  })

  it("пробел после короткого слова в конце строки — на стыке элементов", () => {
    expect(t("Оцените работу в ")).toBe("Оцените работу в~")
  })

  it("перед частицами", () => {
    expect(t("Готово ли решение")).toBe("Готово~ли~решение")
    expect(t("Сделал бы раньше")).toBe("Сделал~бы~раньше")
    expect(t("Тогда же вечером")).toBe("Тогда~же~вечером")
    // «либо» и «жена» — не частицы
    expect(t("Иван жена")).toBe("Иван жена")
  })

  it("перед тире", () => {
    expect(t("Счёт — основной")).toBe("Счёт~— основной")
    expect(t("Срок 1 – 3 дня")).toBe("Срок 1~– 3 дня")
  })

  it("между группами цифр и перед ₽ и %", () => {
    expect(t("Сумма 4 090 000,00 ₽")).toBe("Сумма 4~090~000,00~₽")
    expect(t("40702 810 7 0059 0062573")).toBe("40702~810~7~0059~0062573")
    expect(t("Ставка 12,5 %")).toBe("Ставка 12,5~%")
  })

  it("идемпотентен и не трогает пустую строку", () => {
    const once = typograph("Счёт для оплаты — 4 090 000,00 ₽")
    expect(typograph(once)).toBe(once)
    expect(typograph("")).toBe("")
  })
})
