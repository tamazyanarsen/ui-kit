import * as React from "react"

/**
 * Подставить иконке размерный вариант под её слот.
 *
 * Дизайн-чек от 08.09, замечание 31: «Видно, что в размере иконки 24×24 взят
 * вариант 16×16, что приводит к слишком жирному штриху… Проверить все
 * компоненты на это, везде подобрать размеры исходя из итогового размера.
 * Тогда толщины штрихов гармонизируются».
 *
 * Почему это не решается классом: у иконок кита 16 и 24 — ДВА РАЗНЫХ
 * начертания (в мастере они нарисованы отдельно, штрих у мелкого толще
 * относительно бокса). `className="size-6"` растягивает шестнадцатый до
 * двадцати четырёх вместе со штрихом — отсюда и «слишком жирно». Выбирает
 * начертание проп `size`, а его знает слот, а не вызывающий: плитка меню
 * создания всегда 24, ручка перетаскивания всегда 24.
 *
 * Поэтому слот с фиксированным размером клонирует переданный узел и
 * проставляет `size` сам. Явный `size` у вызывающего сильнее — если кто-то
 * специально просит мелкое начертание, ему не мешают.
 */
function withIconSize(node: React.ReactNode, size: 16 | 24): React.ReactNode {
  if (!React.isValidElement(node)) return node
  const props = node.props as { size?: number }
  if (props.size !== undefined) return node
  return React.cloneElement(node as React.ReactElement<{ size?: number }>, {
    size,
  })
}

export { withIconSize }
