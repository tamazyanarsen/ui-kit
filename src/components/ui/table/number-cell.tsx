import * as React from "react"

import { cn } from "@/lib/utils"

// Числовая ячейка: выравнивание «запятая под запятой», слот знака валюты и
// чистое копирование значения в буфер. Три сюжета связаны одним — тем, что
// у Object Sans нет табличных цифр, — поэтому лежат вместе.

// Неразрывный пробел и правило «чем отделять знак от числа» берутся из
// общего модуля формата чисел (`lib/number-format`): те же два правила
// понадобились полю ввода и ползунку, и держать их у таблицы значило бы
// выбрать не тот слой.
//
// ⚠️ Отбивка НЕ одна на все знаки: `%`, `‰`, `°` набираются вплотную к
// числу, а знак валюты и «шт.» — через неразрывный пробел.
import { NBSP, unitSeparator } from "@/lib/number-format"

/**
 * Ставит каждую цифру в коробку одинаковой ширины — синтез табличных цифр.
 *
 * ⚠️ Нужен потому, что **в Object Sans табличных цифр нет вовсе**: фичи
 * `tnum` в шрифте не существует (проверено по всем поставляемым начертаниям
 * в `src/assets/Object Sans/`), а ширины цифр разные. Браузер синтезировать
 * их не умеет, поэтому `font-variant-numeric: tabular-nums` в этом шрифте —
 * пустая строка, и «запятая под запятой» из него не получается. Второе
 * шрифтовое семейство запрещено правилом проекта, значит одинаковую ширину
 * даёт сама ячейка: цифра встаёт в коробку `1ch` (`ch` — это как раз ширина
 * нуля, самой широкой цифры).
 *
 * Правило `tabular-nums` в CSS при этом оставлено: появится фича в шрифте —
 * заработает без правок здесь.
 *
 * Запятая и минус ширину не меняют — они одинаковы во всех строках колонки,
 * и трогать их не нужно. Не строка — возвращается как есть: разбирать чужие
 * узлы компонент не должен.
 *
 * ## Ширина коробки
 *
 * `0.93ch`, а не `1ch`. `ch` — это ширина нуля, а в Object Sans ноль сильно
 * шире остальных цифр: при 14px ноль занимает 10.26px, восьмёрка 9.27,
 * единица 5.87. Коробка по нулю раздувала число примерно на 16% — дизайнер
 * это и увидел: «цифра под цифрой сейчас хорошо, но надо немного сократить
 * кернинг, чтобы символы были ближе друг к другу».
 *
 * 0.93ch = 9.54px при 14px. Самый широкий глиф (тот же ноль) рисует 9.0px
 * чернил, то есть между соседними нулями остаётся полпикселя — плотно, но
 * без слипания. Ниже опускаться нельзя: на 0.88ch коробка становится равна
 * чернилам нуля и цифры смыкаются.
 *
 * ## Разрядные пробелы
 *
 * `select-none` на разделителе. Дизайн-чек: «При копировании числа с
 * разрядами в текст попадают пробелы, которых не должно быть». Пробел
 * остаётся настоящим символом (ширина и вид не меняются ни на пиксель), но
 * `user-select: none` исключает его из выделения — в буфер уходит
 * «31922980,05 ₽», а не «31 922 980,05 ₽». Работает для любого способа
 * копирования, в том числе когда выделено сразу несколько ячеек.
 *
 * Не любой пробел, а только разрядный: тот, что стоит МЕЖДУ цифрами. Пробел
 * перед знаком валюты — часть значения и копироваться должен.
 */
function withTabularDigits(node: React.ReactNode): React.ReactNode {
  if (typeof node !== "string" && typeof node !== "number") return node
  const text = String(node)
  if (!/\d/.test(text)) return node
  const chars = Array.from(text)
  const isDigit = (char: string | undefined) =>
    char !== undefined && char >= "0" && char <= "9"

  return chars.map((char, index) => {
    if (isDigit(char)) {
      return (
        <span key={index} className="inline-block w-[0.93ch] text-center">
          {char}
        </span>
      )
    }
    if (
      /\s/.test(char) &&
      isDigit(chars[index - 1]) &&
      isDigit(chars[index + 1])
    ) {
      return (
        <span key={index} className="select-none">
          {char}
        </span>
      )
    }
    return char
  })
}

/**
 * Убирает из копируемого значения перенос строки, которого в числе нет.
 *
 * Когда в колонке несколько знаков валюты, слот знака — грид (иначе не
 * зарезервировать ширину по самому широкому глифу, см. `unitVariants`), а
 * элементы грида блочные. Сериализатор выделения ставит перед блочным
 * боксом перенос, и «1 250 000,00 ₽» уходит в буфер как «1 250 000,00\n ₽».
 *
 * Раскладкой это не лечится: перенос даёт ЛЮБОЙ блочный бокс в поддереве —
 * даже скрытый и нулевой высоты. Проверено на inline-grid, на вложенном
 * скрытом inline-grid и на block-близнецах с `height: 0`; чистыми выходят
 * только варианты вообще без блочных боксов в потоке, а они не умеют
 * резервировать ширину по максимуму. Значит, править надо там, где
 * результат виден наверняка, — в самом буфере обмена.
 *
 * Обработчик висит на ячейке-числе, поэтому выделение через несколько ячеек
 * сюда не доходит — событие всплывает выше, и таблица копируется как есть.
 *
 * Убирается не всякий перенос, а ровно этот: слот знака всегда начинается с
 * неразрывного пробела, так что артефакт — это `\n` перед `\u00A0`. Перенос
 * между значением и подписью под ним (`description`) настоящий, его надо
 * оставить, иначе «…,05 ₽» слипается с «Поступление».
 */
function handleNumberCopy(event: React.ClipboardEvent<HTMLTableCellElement>) {
  const text = window.getSelection()?.toString()
  if (!text || !text.includes(`\n${NBSP}`)) return
  event.clipboardData.setData("text/plain", text.replaceAll(`\n${NBSP}`, NBSP))
  event.preventDefault()
}

/**
 * Слот знака (`₽`, `$`, `%`, `шт.`) после числа.
 *
 * Знака нет вовсе (`unit === undefined`) — нет и слота, а пустая ячейка
 * знака не получает никогда: «₽» в одиночестве читается как значение,
 * которого нет, и выравнивать в пустой строке нечего.
 */
function TableCellUnit({
  unit,
  unitVariants,
  hasValue,
}: {
  unit: string | undefined
  unitVariants: string[] | undefined
  hasValue: boolean
}) {
  const variants = React.useMemo(
    () =>
      unit === undefined
        ? []
        : Array.from(new Set([unit, ...(unitVariants ?? [])])).filter(Boolean),
    [unit, unitVariants]
  )

  if (unit === undefined || variants.length === 0 || !hasValue) return null

  // Один знак на колонку (обычный случай) — просто текст в потоке.
  // Резервировать нечего, а коробка со своим `display` вставила бы в
  // выделение перенос строки: значение копировалось бы как
  // «1 250 000,00\n ₽».
  if (variants.length === 1) {
    return <span data-slot="table-cell-unit">{unitSeparator(unit) + unit}</span>
  }

  // Разные знаки в одной колонке — вот тут коробка нужна: видимый вариант и
  // невидимые двойники лежат в ОДНОЙ клетке грида, и она получает ширину
  // самого широкого глифа. Двойники держат ширину, но не читаются ни глазом,
  // ни скринридером (`invisible` = `visibility: hidden` убирает узел и из
  // дерева доступности).
  return (
    <span
      data-slot="table-cell-unit"
      className="inline-grid grid-cols-1 grid-rows-1 justify-items-start align-baseline"
    >
      {variants.map((variant) => (
        <span
          key={variant}
          className={cn(
            "col-start-1 row-start-1 whitespace-pre",
            variant !== unit && "invisible"
          )}
          aria-hidden={variant === unit ? undefined : true}
        >
          {unitSeparator(variant) + variant}
        </span>
      ))}
    </span>
  )
}

export { NBSP, TableCellUnit, handleNumberCopy, withTabularDigits }
