// Общий модуль формата чисел: что считается РАЗРЯДНЫМ разделителем, каким
// пробелом отбивается знак и какие знаки не отбиваются вовсе.
//
// Отдельным местом — потому что одни и те же два правила понадобились в трёх
// компонентах сразу (ячейка таблицы, поле ввода с маской, ползунок), и
// каждый раз чинить их «у себя» значило выбрать не тот слой: жалоба «когда
// копирую сумму — пробелы мне там не нужны» приходила трижды.
//
// Слои разложены так:
//   • ЧТО считается разделителем — здесь;
//   • КАК его снимать в поле ввода — `use-copy-without-separators.ts`;
//   • ячейка таблицы прячет разделитель РАЗМЕТКОЙ (`user-select: none` на
//     самом пробеле), а поля снимают его на самом копировании — внутри поля
//     разметки нет, значение и есть строка.

/** Неразрывный пробел — настоящим символом, а не отступом. */
export const NBSP = "\u00A0"

/**
 * Узкий неразрывный пробел. ICU для `ru-RU` в части сборок отдаёт разряды
 * именно им (U+202F), а не обычным неразрывным. Разница невидима глазом, но
 * ломает всё, что ищет разрядный пробел по символу.
 */
export const NARROW_NBSP = "\u202F"

/** Всё, что в ките может оказаться разрядным пробелом. */
export const GROUP_SPACES = [" ", NBSP, NARROW_NBSP] as const

/** Приводит любой пробел из `Intl` к одному символу — `NBSP`. */
export function normalizeSpaces(text: string) {
  return text.replaceAll(NARROW_NBSP, NBSP)
}

/**
 * Знаки, которые набираются ВПЛОТНУЮ к числу: «50%», «12‰», «17°».
 *
 * Знак валюты и единицы вроде «шт.» — наоборот, через неразрывный пробел:
 * «1 200,00 ₽». Раньше отбивка была одна на всех (0.25em), и процент
 * отрывался от своего числа.
 */
const TIGHT_UNITS = new Set(["%", "‰", "°", "′", "″"])

/** Чем отделять знак от числа: `""` для процентов и градусов, иначе `NBSP`. */
export function unitSeparator(unit: string) {
  return TIGHT_UNITS.has(unit.trim()) ? "" : NBSP
}

/**
 * Приводит готовую строку из `Intl` к отбивке кита.
 *
 * ICU для `ru-RU` отбивает пробелом ВСЁ подряд, включая процент, — а кит
 * ставит `%`, `‰`, `°` вплотную к числу и через неразрывный пробел только
 * знак валюты и единицы вроде «шт.». Заодно разрядные пробелы приводятся к
 * одному символу.
 */
export function formatSignSpacing(text: string) {
  return normalizeSpaces(text).replace(
    new RegExp(`[\\s${NBSP}]+([${[...TIGHT_UNITS].join("")}])`, "gu"),
    "$1"
  )
}

/**
 * Снимает РАЗРЯДНЫЕ пробелы — те, что стоят между цифрами.
 *
 * ⚠️ Разбор идёт по СТРОКЕ целиком, а не по срезу выделения: механика,
 * читающая выделение, обязана давать тот же ответ при выделении с края, а
 * не только посередине — иначе «000 ₽» из хвоста суммы отдавалось бы с
 * мусором.
 *
 * ⚠️ Знак валюты ОСТАЁТСЯ — он часть значения, а не разделитель. Снимается
 * ровно то, что стоит между двумя цифрами.
 *
 * @param separators какие символы маска объявила разделителями. У суммы и
 *   номера карты это пробел, у телефона ещё и дефис: снять один пробел
 *   значило бы отдать `+7912345-67-89`, то есть полуформат.
 */
export function stripGroupSeparators(
  text: string,
  separators: readonly string[] = GROUP_SPACES
) {
  const chars = Array.from(text)
  const isDigit = (char: string | undefined) =>
    char !== undefined && char >= "0" && char <= "9"

  return chars
    .filter((char, index) => {
      if (!separators.includes(char)) return true
      return !(isDigit(chars[index - 1]) && isDigit(chars[index + 1]))
    })
    .join("")
}
