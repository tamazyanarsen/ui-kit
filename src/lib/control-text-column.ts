/**
 * Колонка «подпись + комментарий + ошибка» рядом с контролом формы.
 *
 * Общая для `Checkbox`, `Radio` и `Toggle`: у всех трёх это один и тот же
 * блок справа от коробки (или дорожки), который на мобильном переезжает
 * налево, а на десктопе возвращается на место.
 *
 * Правило нулевого зазора между строками сверено с мастером: сложенные
 * подпись, комментарий и ошибка в сумме дают ровно его собственную высоту,
 * без лишнего просвета.
 *
 * `pt-0.5` (2px) — вертикальная доводка мобильной формы: интерлиньяж строки
 * Option Text там 20px, короче коробки 24px, и без сдвига текст не стоит по
 * центру контрола. На десктопе интерлиньяж уже совпадает, поэтому отступ
 * снимается через `desktop:pt-0`.
 *
 * ⚠️ `min-w-0 flex-1` на ОБОИХ брейкпоинтах, а не `desktop:flex-none`.
 * Дизайн-чек от 08.09, замечание 27: «Чекбокс должен упираться в блок…
 * Сейчас вышел за границу блока. Должен встраиваться и тексты должны
 * переноситься. Правку применить на всех подобных кейсах». С `flex-none`
 * текстовый блок брал ширину содержимого, и длинная подпись («Отказаться от
 * получения последнего транша финансирования по договору подряда») вылезала
 * за правый край блока вместо переноса. `min-w-0` обязателен рядом с
 * `flex-1`: у флекс-элемента автоматический минимум — min-content, и без
 * него перенос всё равно не случился бы.
 *
 * ⚠️ `order-first` — это мобильный переворот строки (дизайн-чек от 07.09,
 * замечания 9 и 25): на мобильном контрол стоит СПРАВА от текста, на
 * десктопе — слева.
 *
 * Переворот сделан именно `order` на текстовом блоке, а не перестановкой в
 * разметке: коробка обязана остаться первой в DOM — за ней ходят `htmlFor`,
 * порядок обхода с клавиатуры и чтение с экрана, и менять их ради
 * оформления нельзя. `flex-1` в мобильной форме заодно прижимает коробку к
 * правому краю строки, а не оставляет её болтаться сразу за текстом.
 *
 * `break-words` — неразрывное слово (номер договора, ссылка) переносится
 * внутри колонки, а не раздвигает строку: `min-w-0` сжимает колонку, но без
 * разрешения рвать слово текст всё равно вылезал за её край.
 */
const CONTROL_TEXT_COLUMN_CLASS =
  "order-first flex min-w-0 flex-1 flex-col break-words pt-0.5 desktop:order-none desktop:pt-0"

export { CONTROL_TEXT_COLUMN_CLASS }
