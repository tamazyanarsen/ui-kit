/**
 * Закрепление нижних полос действий — общее правило для `ButtonMenu` и
 * `ButtonMenuBlack`.
 *
 * Дизайн-чек от 08.09, замечание 9: «Отлипает от края Button Menu и Button
 * Menu Black. Ни при каких условиях в нашем продукте не должны отлипать,
 * прижимаются к нижнему краю вьюпорта. Но на будущее заведи им пропс
 * отлипания… И если отлипает — тогда в момент отлипания добавляются снизу
 * радиусы, такие же как сверху».
 *
 * Отсюда три формы, а не две:
 *
 *   pinned (по умолчанию) — липнет к низу, скругления только сверху, нижней
 *                           рамки нет: край полосы совпадает с краем экрана;
 *   detached              — «отлипшая» полоса: остров в потоке, скругления с
 *                           четырёх сторон и рамка по кругу;
 *   pinned={false}        — полоса просто в потоке (например, внутри
 *                           карточки), геометрия закреплённой.
 *
 * ⚠️ Само «отлипание» в продукте лечится НЕ здесь, а раскладкой страницы:
 * `position: sticky` прижимает элемент к низу СВОЕГО контейнера, и если под
 * контейнером есть отступ (у песочного шелла это был хвост страницы 40px
 * ПОД полосой), полоса честно паркуется над ним. Класс тут ни при чём —
 * см. правку `SandboxPage`, где хвост переехал наверх.
 */

/** Липнет к низу прокручиваемого контейнера. */
const PINNED_CLASS = "sticky bottom-0 z-30"

/**
 * Скругления и рамка по состоянию полосы.
 *
 * `border` возвращает только радиусы и нижнюю грань: боковые и верхняя у
 * белой полосы стоят всегда, а чёрная рамки не имеет вовсе — поэтому она
 * зовёт эту функцию с `bordered: false`.
 */
function barShapeClass({
  detached,
  bordered,
}: {
  detached?: boolean
  bordered?: boolean
}) {
  if (!detached) return "rounded-t-[16px]"
  return bordered
    ? "rounded-[16px] border-b border-solid border-[var(--button-menu-border)]"
    : "rounded-[16px]"
}

export { PINNED_CLASS, barShapeClass }
