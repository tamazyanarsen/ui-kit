/**
 * Предел ширины выпадающих списков навигации: «…» у ButtonMenu, Tabs и
 * Switcher, меню шапки, «Ещё» меню сотрудника.
 *
 * Раньше у списков был только `min-w-*`: попап брал ширину по самой длинной
 * подписи. На телефоне пункт от ~40 символов («Отправить документ на
 * согласование руководителю») раздвигал страницу вбок, а на десктопе один
 * длинный пункт растягивал список до 984px в строку. Теперь список не шире
 * 400px и не шире окна без полей 16px, а подпись внутри переносится (или
 * обрезается, если строка сама `truncate`). `overflow-wrap: anywhere`, а не
 * `break-word`: только он уменьшает минимальную ширину по содержимому, и
 * длинное слово без пробелов тоже не распирает список.
 */
const NAV_POPUP_WIDTH = "max-w-[min(400px,calc(100vw-32px))] [overflow-wrap:anywhere]"

export { NAV_POPUP_WIDTH }
