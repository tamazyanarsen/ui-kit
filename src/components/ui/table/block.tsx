import * as React from "react"

import { cn } from "@/lib/utils"

// TableBlock — «Анатомия табличных блоков». Макет собирает табличный блок
// страницы сверху вниз так:
//
//   Название (опционально) → Вкладки (опционально) → Блок фильтрации
//   (опционально) → Сводка (есть всегда) и настройка нижестоящего контента
//   (опционально) → Шапка → Блок с данными или пустым результатом →
//   Пагинатор (опционально)
//
// и про сам контейнер говорит прямо: «Для табличных блоков заливка
// white 101, padding = 0px, gap = 0px. Для элементов внутри блока итоговый
// горизонтальный padding = 16px, радиусы скруглений 16px».
//
// То есть здесь только карточка: отступ 16px принадлежит элементам внутри
// неё (`TableTop` и так несёт свой p-16, `Pagination` — свой), а линии между
// разделами — это нижние рамки, которые уже рисуют шапка и строки. Подрезка
// по радиусу — то, что держит заливки строк во всю ширину внутри 16px
// скругления.
//
// ⚠️ Подрезка именно `overflow-clip`, а не `overflow-hidden`. Дизайн-чек от
// 07.09, замечание 32: «У таблиц всегда должна закрепляться нижняя полоса
// горизонтальной прокрутки». Полоса — `sticky bottom-0`, а `overflow:
// hidden` делает блок ПРОКРУЧИВАЕМОЙ областью: липкий потомок начинает
// считаться от неё, а не от вьюпорта, и полоса замирала у нижней кромки
// блока — на реестре аккредитивов это 733px ниже нижнего края экрана.
// `overflow: clip` режет по тому же радиусу, но области прокрутки не
// создаёт. То же исправлено у `CardBox type="table"` и у песочного блока.
const TableBlock = React.forwardRef<
  HTMLDivElement,
  React.ComponentProps<"div">
>(function TableBlock({ className, ...props }, ref) {
  return (
    <div
      ref={ref}
      data-slot="table-block"
      className={cn(
        "w-full overflow-clip rounded-[16px] bg-[var(--table-bg)]",
        className
      )}
      {...props}
    />
  )
})

// Слот пустого или нулевого результата — «Нулевой результат фильтрации, нет
// записей. Замещают собой строки таблицы внутри блока».
//
// Он намеренно стоит *вне* области горизонтальной прокрутки таблицы, потому
// что макет прямо требует, чтобы он с ней не двигался: «Горизонтальная
// прокрутка не прокручивает элементы пустых состояний — информация всегда
// размещается по центру блока по горизонтали». Строка шапки над ним
// остаётся как есть («Конструкция таблицы (фильтры, заголовки и тд) остаётся
// без изменений, так как на страницах может быть онбординг на элементы
// таблиц»), а нижняя линия отделяет пагинатор так же, как это делала бы
// последняя строка данных.
const TableBlockEmpty = React.forwardRef<
  HTMLDivElement,
  React.ComponentProps<"div">
>(function TableBlockEmpty({ className, ...props }, ref) {
  return (
    <div
      ref={ref}
      data-slot="table-block-empty"
      className={cn(
        "flex w-full items-center justify-center border-b border-[var(--table-divider)]",
        className
      )}
      {...props}
    />
  )
})

export { TableBlock, TableBlockEmpty }
