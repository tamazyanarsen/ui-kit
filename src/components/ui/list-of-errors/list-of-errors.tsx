import * as React from "react"

import { Divider } from "@/components/ui/divider"
import { cn } from "@/lib/utils"

// List of Errors — список проблем (`ELK / list-errors`, компонент-сет
// 70427:3561, он же 70441:26335 на странице `03. ELK / list-errors`
// 70441:26299 — это одна и та же нода в двух раскладках копии; Version
// 1.0.0, Release 68.34): разделитель во всю ширину + зазор + коробка строк
// с зазором 8 между ними.
//
// Сверено повторно 23.09 по странице 70441:26299 — расхождений нет:
// Desktop Value=5 даёт 176 при строке 24 и зазоре 23, Mobile Value=5 —
// 148 при строке 20 и зазоре 15 (замерено в Storybook, не выведено).
//
// Дизайн-чек от 13.09, замечание 9: «Переименовать Issue List в List of
// Errors и перепроверить. Компонент добавлен в ДС, пересобрать на его
// основе». Сверено по мастеру целиком (ноды в доступной копии
// `lSQi6Xn5HHrt1yvGCIFPZb`), и десктопная форма сошлась один в один —
// изменилась только МОБИЛЬНАЯ: у сета есть ось `Size`, которой в ките не
// было.
//
// Оси сета: `Size` (Desktop | Mobile) × `Value` (1…5).
//
//   Desktop  зазор 23, строка 24 → 48 / 80 / 112 / 144 / 176
//   Mobile   зазор 15, строка 20 → 36 /  64 /  92 / 120 / 148
//
// ⚠️ Зазоры 23 и 15 — не промах дизайнера, и «исправлять» их на 24 и 16
// нельзя. Линия 1px стоит В ПОТОКЕ, поэтому от кромки линии до текста
// получается ровно 24 и 16: 1 + 23 + 24 = 48, 1 + 15 + 20 = 36.
//
// Документация сета: «Error — текст ошибки, блокирующее состояние;
// Attention — текст предупреждения, не блокирующего подписание;
// Information — информационное сообщение. Опциональные элементы: Divider.
// Количество ошибок от 1 до 5».
//
// Свойство `Value` (1…5) из сета пропом НЕ становится — это перечисленные
// примеры количества, а количество приходит содержимым.
//
// Разделитель принадлежит СПИСКУ, а не строке (так он лежит в сете):
// одиночная строка линии не рисует, два списка подряд дадут две линии.

interface ListOfErrorsProps extends React.ComponentProps<"div"> {
  /**
   * Показывать разделитель над списком.
   *
   * Документация сета прямо называет его опциональным («Опциональные
   * элементы: Divider»), умолчание — «показывать», как во всех символах:
   * список ставится и там, где линия уже есть выше.
   *
   * Отдельного правила отступа выключение не потребовало: зазор объявлен
   * МЕЖДУ линией и коробкой строк, и при одном ребёнке flex его не рисует —
   * то есть выключение убирает и линию, и отступ разом (замер: 80 и 24 с
   * линией против 56 и 0 без неё).
   */
  showDivider?: boolean
}

function ListOfErrors({
  showDivider = true,
  className,
  children,
  ...props
}: ListOfErrorsProps) {
  const items = React.Children.toArray(children)

  return (
    <div
      data-slot="list-of-errors"
      className={cn("flex flex-col gap-[15px] desktop:gap-[23px]", className)}
      {...props}
    >
      {showDivider && <Divider />}
      <ul data-slot="list-of-errors-items" className="flex flex-col gap-2">
        {items.map((child, index) => (
          <li
            key={index}
            data-slot="list-of-errors-item"
            className="motion-safe:animate-[issue-item-in_200ms_ease-out_both]"
            // Лесенка 40 мс по первым четырём строкам, дальше задержка
            // держится на 160 мс: иначе пятая строка обгоняет первые
            // четыре, и вместо «проблем несколько, читать сверху» список
            // проявляется как попало.
            style={{ animationDelay: `${Math.min(index, 4) * 40}ms` }}
          >
            {child}
          </li>
        ))}
      </ul>
    </div>
  )
}

export { ListOfErrors }
export type { ListOfErrorsProps }
