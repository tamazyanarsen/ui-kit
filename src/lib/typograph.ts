/**
 * Типограф: расставляет неразрывные пробелы (U+00A0), чтобы при переносе
 * строки короткие слова не оставались в конце строки, тире не начинало
 * строку, а суммы и номера счетов не разрывались между группами цифр.
 *
 * Правки UI-Kit от 25.10, правило каркаса «Типограф — без висячих
 * предлогов, союзов и частиц». Правило системное, но кит НЕ обходит DOM сам
 * (глобального MutationObserver здесь нет): текст прогоняется через
 * `typograph()` там, где он выводится или готовится, — в данных экрана, в
 * подписях, в ответе сервера. Поля ввода, код и скрытые подписи для экранного
 * диктора обрабатывать не нужно — туда функцию просто не передают.
 *
 * Стык элементов («в» + ссылка «ЕЛК»): пробел после короткого слова в конце
 * строки тоже становится неразрывным, поэтому пробел между элементами держите
 * в конце первой строки — `{typograph("Оцените работу в ")}<Link>ЕЛК</Link>`.
 *
 * Функция чистая и идемпотентная: повторный прогон ничего не меняет.
 */

const NBSP = " "

/** Предлоги и союзы длиннее двух букв, после которых пробел неразрывный. */
const BOUND_WORDS = [
  "без", "безо", "для", "изо", "меж", "над", "надо", "под", "подо", "пред",
  "при", "про", "через", "перед", "между", "около", "ради", "или", "либо",
  "что", "чтобы", "как", "так", "если", "когда", "чем",
  // Форма собственности не отрывается от названия.
  "ооо", "пао",
]

const LETTER = "\\p{L}"
const WORD_CHAR = "[\\p{L}\\p{N}]"

// Слово из 1–2 букв или слово из списка, не продолжающее другое слово
// (`кто-то` не трогаем: перед «то» дефис), и пробелы после него.
const AFTER_SHORT = new RegExp(
  `(?<![\\p{L}\\p{N}\\-])(${LETTER}{1,2}|${BOUND_WORDS.join("|")}) +`,
  "giu"
)

// Пробелы перед частицей ли, ль, же, ж, бы, б (отдельным словом).
const BEFORE_PARTICLE = new RegExp(`(?<=\\S) +(?=(?:ли|ль|же|ж|бы|б)(?!${WORD_CHAR}))`, "giu")

// Пробелы перед тире (длинным и коротким).
const BEFORE_DASH = / +(?=[—–])/g

// Между группами цифр и между числом и ₽ или %.
const IN_NUMBER = /(?<=\d) +(?=[\d₽%])/g

function typograph(text: string): string {
  if (!text) return text
  return text
    .replace(AFTER_SHORT, (_, word: string) => word + NBSP)
    .replace(BEFORE_PARTICLE, NBSP)
    .replace(BEFORE_DASH, NBSP)
    .replace(IN_NUMBER, NBSP)
}

export { typograph, NBSP }
